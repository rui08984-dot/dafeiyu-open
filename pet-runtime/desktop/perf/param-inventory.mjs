/**
 * 用权威表校验运行时参数范围。
 * @param {Map<string,[number,number]>} ranges
 * @param {(id:string)=>boolean} [hasParam] 不传则按 ranges 自身判断
 * @returns {{checked:number, mismatched:Array, missing:Array}}
 */
export function validateRanges(ranges, hasParam) {
  const mismatched = [];
  const missing = [];
  let checked = 0;
  for (const [id, spec] of Object.entries(PARAM_TABLE)) {
    if (hasParam && !hasParam(id)) { missing.push(id); continue; }
    const got = ranges && ranges.get ? ranges.get(id) : null;
    if (!got) { missing.push(id); continue; }
    checked += 1;
    const [lo, hi] = got;
    if (Math.abs(lo - spec.min) > 1e-6 || Math.abs(hi - spec.max) > 1e-6) {
      mismatched.push({ id, expected: [spec.min, spec.max], got: [lo, hi] });
    }
  }
  return { checked, mismatched, missing };
}
